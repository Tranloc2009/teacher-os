function buildReadyMixedExam() {
  const ready = structuredClone(DEMO_MATH_EXAM);
  ready.confirmedOriginalAnswers = true;
  ready.questions = ready.questions.map((q) => ({ ...q, answerConfirmed: true }));
  ready.mixConfig = {
    ...ready.mixConfig,
    examCount: 2,
    startCodeNumber: 101,
    seed: 'phase-d-azota-test',
  };
  const mixed = generateMixedExams(ready);
  assert.ok(mixed.versions.length >= 2);
  return { ...ready, generatedVersions: mixed.versions };
}

