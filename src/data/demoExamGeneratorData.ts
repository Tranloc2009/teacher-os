const SEED_ISO = '2026-09-01T08:00:00.000Z';

function makeMcqQuestion(params: {
  id: string;
  code: string;
  subjectId: 'toan' | 'vat-ly';
  topic: string;
  cognitiveLevel: MathQuestion['cognitiveLevel'];
  points: number;
  stem: string;
  options: [string, string, string, string];
  correctIndex: 0 | 1 | 2 | 3;
  solution: string;
  answerConfirmed?: boolean;
  hasVisualAsset?: boolean;
  visualSvg?: string;
}): MathQuestion {
  const labels = ['A', 'B', 'C', 'D'] as const;
  const opts = params.options.map((text, idx) => ({
    id: `${params.id}-opt-${labels[idx].toLowerCase()}`,
    originalLabel: labels[idx],
    content: parseMathContent(text, `${params.id}-o${idx}`),
    isCorrect: idx === params.correctIndex,
  }));
  const visualAssets = params.visualSvg
    ? [
        createMathVisualAsset({
          id: `${params.id}-vis-1`,
          kind: 'geometry-svg',
          label: 'Hình minh họa hình học phẳng (bảo vệ nguyên vẹn)',
          sourceData: params.visualSvg,
        }),
      ]
    : undefined;

  return {
    id: params.id,
    code: params.code,
    sectionTitle: MATH_SECTION_TITLES.mcq,
    type: 'mcq',
    universalType: 'mcq',
    subjectId: params.subjectId,
    topic: params.topic,
    cognitiveLevel: params.cognitiveLevel,
    difficultyScore:
      params.cognitiveLevel === 'nhan-biet'
        ? 1
        : params.cognitiveLevel === 'thong-hieu'
        ? 2
        : params.cognitiveLevel === 'van-dung'
        ? 3
        : 4,
    points: params.points,
    stem: parseMathContent(params.stem, `${params.id}-stem`),
    options: opts,
    correctOptionId: opts[params.correctIndex].id,
    solutionGuide: parseMathContent(params.solution, `${params.id}-sol`),
    ...(visualAssets ? { visualAssets } : {}),
    lockQuestionPosition: false,
    lockOptionShuffle: false,
    allowStatementShuffle: false,
    dependencyFlags: [],
    hasVisualAsset: Boolean(params.hasVisualAsset || visualAssets),
    answerConfirmed: params.answerConfirmed ?? true,
    createdAt: SEED_ISO,
    updatedAt: SEED_ISO,
  };
}

